function table_out = l2f_eval_sample_table(dynamics, metrics, long_metrics)
%L2F_EVAL_SAMPLE_TABLE Build the per-sample position-hold evaluation table.

count = metrics.count;
sample_id = (1:count).';
position_hold_steady = double(metrics.position_hold_steady(:));
position_hold_snapshot = double(metrics.position_hold_snapshot(:));
final_window_success_fraction = metrics.final_window_success_fraction(:);
settling_time = metrics.position_hold_settling_time_s(:);
stay = metrics.position_hold_stay_fraction(:);
survival = double(metrics.survival(:));
dyn = dynamics;

mass = dyn(:, 1);
thrust_to_weight = dyn(:, 17);
torque_to_inertia = dyn(:, 18);
motor_time_rising = dyn(:, 21);
motor_time_falling = dyn(:, 22);
cbrt_mass = dyn(:, 24);
force_std = dyn(:, 25);
arm_length_m = dyn(:, 26);
inertia_x = dyn(:, 27);
inertia_y = dyn(:, 28);
inertia_z = dyn(:, 29);
alpha_roll_max = dyn(:, 30);
alpha_yaw_max = dyn(:, 32);
eta_yaw = dyn(:, 33);
jz_over_jxy = dyn(:, 34);

% Required equilibrium tilt is retained strictly as a physics diagnostic.
external_force_x = dyn(:, 14);
external_force_y = dyn(:, 15);
external_force_z = dyn(:, 16);
force_xy = hypot(external_force_x, external_force_y);
vertical_support = mass .* metrics.gravity - external_force_z;
required_tilt_deg = atan2(force_xy, max(vertical_support, 1.0e-12)) * 180 / pi;

table_out = table( ...
    sample_id, position_hold_steady, position_hold_snapshot, ...
    final_window_success_fraction, settling_time, stay, survival, ...
    mass, cbrt_mass, arm_length_m, 2.0 * arm_length_m, ...
    thrust_to_weight, torque_to_inertia, ...
    motor_time_rising, motor_time_falling, ...
    force_std, inertia_x, inertia_y, inertia_z, ...
    alpha_roll_max, alpha_yaw_max, eta_yaw, jz_over_jxy, ...
    metrics.position_final(:), metrics.velocity_final(:), metrics.omega_final(:), ...
    metrics.position_max(:), metrics.velocity_max(:), metrics.omega_max(:), ...
    metrics.control_energy(:), ...
    external_force_x, external_force_y, external_force_z, required_tilt_deg, ...
    'VariableNames', { ...
        'sample_id', 'position_hold_steady', 'position_hold_snapshot', ...
        'final_window_success_fraction', 'settling_time', 'stay', 'survival', ...
        'mass_kg', 'cbrt_mass', 'arm_length_m', 'motor_span_m', ...
        'thrust_to_weight', 'torque_to_inertia', ...
        'motor_time_rising_s', 'motor_time_falling_s', ...
        'force_std', 'inertia_x', 'inertia_y', 'inertia_z', ...
        'alpha_roll_max', 'alpha_yaw_max', 'eta_yaw', 'jz_over_jxy', ...
        'position_final_m', 'velocity_final', 'omega_final', ...
        'position_max_m', 'velocity_max', 'omega_max', 'control_energy', ...
        'external_force_x', 'external_force_y', 'external_force_z', ...
        'required_tilt_deg' ...
    });
if nargin >= 3 && isstruct(long_metrics) && isfield(long_metrics, 'sample') ...
        && istable(long_metrics.sample) && height(long_metrics.sample) == height(table_out)
    table_out = [table_out, long_metrics.sample];
end
end
